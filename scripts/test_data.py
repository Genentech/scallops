"""Manage scallops test data stored as GitHub release assets.

Usage::

    python scripts/test_data.py download   # fetch missing/outdated files
    python scripts/test_data.py upload     # rebuild registry, upload new files (needs gh)

Data is downloaded to the scallops cache directory (``SCALLOPS_CACHE_DIR`` or the
platform default, e.g. ``~/.cache/scallops``); ``--data-dir`` overrides it. Each file is
an asset of the ``test-data`` release, and ``scallops/datasets/registry.txt`` records
its sha256.

To add or change test data: put the file under the data directory, run
``upload``, then commit the updated ``registry.txt``. Assets are never deleted
(names include the hash), so older commits can still download their data.
"""

import argparse
import importlib.util
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Load _registry.py directly so this script doesn't need scallops installed.
_spec = importlib.util.spec_from_file_location(
    "_registry", ROOT / "scallops" / "datasets" / "_registry.py"
)
if _spec is None or _spec.loader is None:
    raise ImportError("Unable to load scallops/datasets/_registry.py")
registry = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(registry)


def _gh(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["gh", *args, "--repo", registry.REPO],
        check=check,
        capture_output=True,
        text=True,
    )


def write_registry(data_dir: Path) -> dict[str, str]:
    if not data_dir.is_dir():
        raise SystemExit(f"Data directory not found: {data_dir}")
    entries = {}
    for path in sorted(data_dir.rglob("*")):
        if path.is_file() and not path.name.startswith("."):
            rel = path.relative_to(data_dir).as_posix()
            entries[rel] = registry.file_sha256(path)
    if not entries:
        raise SystemExit(f"No files found in {data_dir}; registry not written")
    with open(registry.REGISTRY_PATH, "w") as f:
        f.write(
            "# sha256 path (relative to the data directory). "
            "Generated by scripts/test_data.py\n"
        )
        for rel, sha in entries.items():
            f.write(f"{sha} {rel}\n")
    print(f"Wrote {len(entries)} entries to {registry.REGISTRY_PATH}")
    return entries


def upload(data_dir: Path) -> None:
    entries = write_registry(data_dir)
    tag = registry.RELEASE_TAG
    if _gh("release", "view", tag, check=False).returncode != 0:
        _gh(
            "release",
            "create",
            tag,
            "--title",
            "Test data",
            "--notes",
            "Test and example data for scallops. Managed by scripts/test_data.py; "
            "do not delete assets.",
            "--latest=false",
        )
        print(f"Created release {tag}")
    existing = {
        a["name"]
        for a in json.loads(_gh("release", "view", tag, "--json", "assets").stdout)[
            "assets"
        ]
    }
    todo = {
        registry.asset_name(rel, sha): rel
        for rel, sha in entries.items()
        if registry.asset_name(rel, sha) not in existing
    }
    print(f"{len(existing)} assets on release, uploading {len(todo)}")
    with tempfile.TemporaryDirectory() as tmp:
        for name, rel in todo.items():
            staged = Path(tmp) / name
            shutil.copyfile(data_dir / rel, staged)
            _gh("release", "upload", tag, str(staged))
            staged.unlink()
            print(f"  uploaded {rel} -> {name}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", choices=["download", "upload"])
    parser.add_argument(
        "--data-dir",
        type=Path,
        default=registry.cache_dir(),
        help="Data directory (default: %(default)s)",
    )
    args = parser.parse_args()
    if args.command == "download":
        registry.fetch(args.data_dir, verbose=True)
    else:
        upload(args.data_dir)


if __name__ == "__main__":
    main()
